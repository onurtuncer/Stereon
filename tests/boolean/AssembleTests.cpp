OperationResult Run(const Shape& a, const Shape& b, const BooleanOperation operation)
{
    auto result = Boolean(a, b, operation, ctx);
    const std::string error = result ? std::string() : std::string(result.error().GetMessage());
    INFO(std::string(Stereon::ToString(operation)) << ": " << error);
    REQUIRE(result.has_value());
    REQUIRE(Stereon::ValidateTopology(result->Shape).IsValid());
    REQUIRE(result->Checked == Stereon::ValidityLevel::Geometric);
    return std::move(*result);
}

/// Whether the point lies inside the result, by its own winding number.
bool Inside(const Shape& shape, const Point3& p)
{
    const auto w = WindingNumberOf(shape, p, 8, ctx);
    const std::string error = w ? std::string() : std::string(w.error().GetMessage());
    INFO(p.X << ", " << p.Y << ", " << p.Z << ": " << error);
    REQUIRE(w.has_value());
    REQUIRE(w->IsDecided());
    return w->IsInside();
}

Shape Corner()
{
    const auto other =
        MakeBoxSolid(Box3::FromCorners(Point3{5.0, 5.0, 5.0}, Point3{15.0, 15.0, 15.0}), ctx);
    REQUIRE(other.has_value());
    return other->Shape;
}

Shape Through()
{
    const auto drum = MakeCylinderSolid(Point3{5.0, 5.0, -2.0}, Vec3{1.0, 0.0, 0.0},
                                        Vec3{0.0, 1.0, 0.0}, 3.0, 15.0, ctx);
    REQUIRE(drum.has_value());
    return drum->Shape;
}

/// The History's entries of one input.
std::size_t EntriesOfInput(const OperationResult& result, const std::uint8_t input)
{
    std::size_t n = 0;
    for (const HistoryEntry& e : result.History.GetEntries()) {
        n += e.Input == input ? 1 : 0;
    }
    return n;
}

