// Assembly (M8, ADR-0013, ADR-0030): union, cut and common of two boxes
// overlapping at a corner, of a box and a cylinder through it, and of bodies
// apart. Each result is checked by its faces and solids and, since a face
// count proves little about which side is kept, by its own winding number
// at points known to be inside or outside it: the result's faces must close
// up, outward, into the solid the operation names. And its History accounts
// for both operands, the intersection edges Generated by the faces that met.

